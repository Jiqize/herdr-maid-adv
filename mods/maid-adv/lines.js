// 稳定挑一句：同一个 key 总是同一句
export function pick(list, key) {
  if (!list?.length) return "";
  let h = 0;
  for (const c of String(key)) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return list[h % list.length];
}

export function fill(text, vars) {
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

