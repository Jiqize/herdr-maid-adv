// 播放状态机：步骤是 第 1 幕台词 → 第 2 幕台词 → 选项 → 结局台词 → （好结局）CG → 完
//   step()：{ kind: "line", act, bg, mood, text } | { kind: "choice", act, bg, choices } | { kind: "cg" } | { kind: "end", good }
export class StoryPlayer {
  constructor(story) {
    this.story = story;
    this.pos = 0;
    this.good = null;
  }

  steps() {
    const s = this.story;
    const out = [];
    s.acts.forEach((a, i) => a.lines.forEach((l) => out.push({ kind: "line", act: i + 1, bg: a.bg, ...l })));
    const last = s.acts[s.acts.length - 1];
    out.push({ kind: "choice", act: s.acts.length, bg: last.bg, choices: s.choices });
    if (this.good === null) return out;
    const end = this.good ? s.good : s.bad;
    end.lines.forEach((l) => out.push({ kind: "line", act: s.acts.length + 1, bg: end.bg, ...l }));
    if (this.good) out.push({ kind: "cg" });
    out.push({ kind: "end", good: this.good });
    return out;
  }

  step() {
    return this.steps()[this.pos];
  }

  // 点一下往下走；停在选项上要用 choose()，到「完」就不动
  next() {
    const k = this.step().kind;
    if (k === "choice" || k === "end") return false;
    this.pos += 1;
    return true;
  }

  choose(i) {
    if (this.step().kind !== "choice") return false;
    this.good = Boolean(this.story.choices[i]?.good);
    this.pos += 1;
    return true;
  }

  restart() {
    this.pos = 0;
    this.good = null;
  }
}
